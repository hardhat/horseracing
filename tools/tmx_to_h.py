#!/usr/bin/env python3
"""
tmx_to_h.py — Convert a Tiled .tmx file to a C header with tile indices
remapped to vontraps in-game tileset indices.

Tileset name → vontraps TILE_COLOR_* base (must match main.h):
    map      → TILE_COLOR_MAP     = 52
    title    → TILE_COLOR_TITLE   = 18
    hud      → TILE_COLOR_HUD     = 116
    sprites  → TILE_COLOR_SPRITES = 140

Usage:
    python3 tools/tmx_to_h.py level/level1.tmx src/level1.h
"""

import os
import sys
import xml.etree.ElementTree as ET

# ---------------------------------------------------------------------------
# Configuration — keep in sync with TILE_COLOR_* in src/main.h
# ---------------------------------------------------------------------------
TSX_BASE = {
    'map':     52,   # TILE_COLOR_MAP
    'title':   18,   # TILE_COLOR_TITLE
    'hud':    116,   # TILE_COLOR_HUD
    'sprites': 140,  # TILE_COLOR_SPRITES
}

EMPTY_TILE = 0   # TILE_COLOR_BLACK


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def build_ranges(tmx_root, tmx_dir):
    """Return list of (firstgid, lastgid, vontraps_base) from the TMX header."""
    ranges = []
    for ts_elem in tmx_root.findall('tileset'):
        firstgid = int(ts_elem.attrib['firstgid'])
        source   = ts_elem.attrib.get('source', '')
        name     = os.path.splitext(os.path.basename(source))[0]
        if name not in TSX_BASE:
            print(f"Warning: unknown tileset '{name}' — skipping", file=sys.stderr)
            continue
        tsx_path = os.path.join(tmx_dir, source)
        tsx_root = ET.parse(tsx_path).getroot()
        tilecount = int(tsx_root.attrib['tilecount'])
        ranges.append((firstgid, firstgid + tilecount - 1, TSX_BASE[name]))
        print(f"  {name}: GIDs {firstgid}–{firstgid+tilecount-1} → "
              f"vontraps {TSX_BASE[name]}–{TSX_BASE[name]+tilecount-1}")
    return ranges


def remap(gid, ranges):
    if gid == 0:
        return EMPTY_TILE
    for (lo, hi, base) in ranges:
        if lo <= gid <= hi:
            return base + (gid - lo)
    raise ValueError(f"GID {gid} not covered by any tileset")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    if len(sys.argv) != 3:
        print("Usage: tmx_to_h.py <input.tmx> <output.h>")
        sys.exit(1)

    tmx_path = sys.argv[1]
    out_path = sys.argv[2]

    tree = ET.parse(tmx_path)
    root = tree.getroot()

    width  = int(root.attrib['width'])
    height = int(root.attrib['height'])
    print(f"Map: {width}×{height} tiles")

    tmx_dir = os.path.dirname(os.path.abspath(tmx_path))
    ranges  = build_ranges(root, tmx_dir)

    # Parse CSV tile data from the first layer
    layer = root.find('layer')
    data  = layer.find('data')
    if data.attrib.get('encoding') != 'csv':
        print("Error: only CSV encoding is supported", file=sys.stderr)
        sys.exit(1)

    gids  = [int(v.strip()) for v in data.text.replace('\n', ',').split(',') if v.strip()]
    if len(gids) != width * height:
        print(f"Error: expected {width * height} tiles, got {len(gids)}", file=sys.stderr)
        sys.exit(1)

    tiles = [remap(g, ranges) for g in gids]

    # Derive C identifiers from the output filename
    level_name = os.path.splitext(os.path.basename(out_path))[0]  # e.g. "level1"
    guard      = level_name.upper() + '_H'
    arr_name   = level_name + '_map'

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, 'w') as f:
        f.write(f'#ifndef {guard}\n')
        f.write(f'#define {guard}\n\n')
        f.write(f'#include <stdint.h>\n\n')
        f.write(f'/* Generated by tools/tmx_to_h.py from {os.path.basename(tmx_path)}'
                f' — do not edit. */\n\n')
        f.write(f'#define {level_name.upper()}_WIDTH  {width}\n')
        f.write(f'#define {level_name.upper()}_HEIGHT {height}\n\n')
        f.write(f'static const uint8_t {arr_name}[{height}][{width}] = {{\n')
        for row in range(height):
            row_tiles = tiles[row * width : (row + 1) * width]
            row_str   = ', '.join(f'{t:3d}' for t in row_tiles)
            f.write(f'    {{ {row_str} }},\n')
        f.write('};\n\n')
        f.write(f'#endif /* {guard} */\n')

    print(f"Wrote {out_path}")


if __name__ == '__main__':
    main()
